`timescale 1ns/1ps

module ai_dot4 (

    input      [31:0] a,
    input      [31:0] b,

    output reg [31:0] result

);

    // =========================================================
    // Four signed INT8 operands
    // =========================================================

    reg signed [7:0] a0;
    reg signed [7:0] a1;
    reg signed [7:0] a2;
    reg signed [7:0] a3;

    reg signed [7:0] b0;
    reg signed [7:0] b1;
    reg signed [7:0] b2;
    reg signed [7:0] b3;


    // =========================================================
    // INT8 multiplication results
    //
    // 8-bit × 8-bit = 16-bit
    // =========================================================

    reg signed [15:0] product0;
    reg signed [15:0] product1;
    reg signed [15:0] product2;
    reg signed [15:0] product3;


    // =========================================================
    // 32-bit accumulator
    // =========================================================

    reg signed [31:0] accumulator;


    // =========================================================
    // Combinational DOT4 engine
    // =========================================================

    always @(*) begin

        // -----------------------------------------------------
        // Unpack A
        // -----------------------------------------------------

        a0 = a[7:0];
        a1 = a[15:8];
        a2 = a[23:16];
        a3 = a[31:24];


        // -----------------------------------------------------
        // Unpack B
        // -----------------------------------------------------

        b0 = b[7:0];
        b1 = b[15:8];
        b2 = b[23:16];
        b3 = b[31:24];


        // -----------------------------------------------------
        // Four parallel multiplications
        // -----------------------------------------------------

        product0 = a0 * b0;
        product1 = a1 * b1;
        product2 = a2 * b2;
        product3 = a3 * b3;


        // -----------------------------------------------------
        // Accumulate
        // -----------------------------------------------------

        accumulator =
            product0 +
            product1 +
            product2 +
            product3;


        // -----------------------------------------------------
        // Output
        // -----------------------------------------------------

        result = accumulator;

    end

endmodule