`timescale 1ns/1ps

module ai_stream_controller (

    input clk,
    input rst,

    // =========================================================
    // CONTROL
    // =========================================================

    input start,

    output reg busy,
    output reg done,


    // =========================================================
    // MATRIX A
    //
    // Each 32-bit word:
    //
    // [31:24] = column 3
    // [23:16] = column 2
    // [15:8]  = column 1
    // [7:0]   = column 0
    // =========================================================

    input [31:0] matrix_a0,
    input [31:0] matrix_a1,
    input [31:0] matrix_a2,
    input [31:0] matrix_a3,


    // =========================================================
    // MATRIX B
    //
    // Each 32-bit word represents one ROW of B.
    // =========================================================

    input [31:0] matrix_b0,
    input [31:0] matrix_b1,
    input [31:0] matrix_b2,
    input [31:0] matrix_b3,


    // =========================================================
    // A STREAM
    // =========================================================

    output reg signed [7:0] a0,
    output reg signed [7:0] a1,
    output reg signed [7:0] a2,
    output reg signed [7:0] a3,


    // =========================================================
    // B STREAM
    // =========================================================

    output reg signed [7:0] b0,
    output reg signed [7:0] b1,
    output reg signed [7:0] b2,
    output reg signed [7:0] b3,


    // =========================================================
    // SYSTOLIC ENABLE
    // =========================================================

    output reg compute_enable

);


    // =========================================================
    // STATES
    // =========================================================

    localparam STATE_IDLE  = 2'b00;
    localparam STATE_STREAM = 2'b01;
    localparam STATE_FLUSH = 2'b10;
    localparam STATE_DONE  = 2'b11;


    reg [1:0] state;

    reg [3:0] cycle;


    // =========================================================
    // STORED MATRIX VALUES
    // =========================================================

    reg [31:0] A0_reg;
    reg [31:0] A1_reg;
    reg [31:0] A2_reg;
    reg [31:0] A3_reg;

    reg [31:0] B0_reg;
    reg [31:0] B1_reg;
    reg [31:0] B2_reg;
    reg [31:0] B3_reg;


    // =========================================================
    // SEQUENTIAL FSM
    // =========================================================

    always @(posedge clk or posedge rst) begin

        if (rst) begin

            state <= STATE_IDLE;

            cycle <= 4'd0;

            A0_reg <= 32'd0;
            A1_reg <= 32'd0;
            A2_reg <= 32'd0;
            A3_reg <= 32'd0;

            B0_reg <= 32'd0;
            B1_reg <= 32'd0;
            B2_reg <= 32'd0;
            B3_reg <= 32'd0;

        end

        else begin

            case (state)

                // =================================================
                // IDLE
                // =================================================

                STATE_IDLE: begin

                    cycle <= 4'd0;

                    if (start) begin

                        A0_reg <= matrix_a0;
                        A1_reg <= matrix_a1;
                        A2_reg <= matrix_a2;
                        A3_reg <= matrix_a3;

                        B0_reg <= matrix_b0;
                        B1_reg <= matrix_b1;
                        B2_reg <= matrix_b2;
                        B3_reg <= matrix_b3;

                        state <= STATE_STREAM;

                    end

                end


                // =================================================
                // STREAM
                //
                // Seven cycles:
                //
                // 0 1 2 3 4 5 6
                // =================================================

                STATE_STREAM: begin

                    if (cycle == 4'd6) begin

                        cycle <= 4'd0;

                        state <= STATE_FLUSH;

                    end

                    else begin

                        cycle <= cycle + 1'b1;

                    end

                end


                // =================================================
                // FLUSH
                // =================================================

                STATE_FLUSH: begin

                    if (cycle == 4'd2) begin

                        cycle <= 4'd0;

                        state <= STATE_DONE;

                    end

                    else begin

                        cycle <= cycle + 1'b1;

                    end

                end


                // =================================================
                // DONE
                // =================================================

                STATE_DONE: begin

                    state <= STATE_IDLE;

                    cycle <= 4'd0;

                end


                default: begin

                    state <= STATE_IDLE;

                    cycle <= 4'd0;

                end

            endcase

        end

    end


    // =========================================================
    // COMBINATIONAL OUTPUT LOGIC
    // =========================================================

    always @(*) begin

        // =====================================================
        // DEFAULTS
        // =====================================================

        busy = 1'b0;

        done = 1'b0;

        compute_enable = 1'b0;

        a0 = 8'sd0;
        a1 = 8'sd0;
        a2 = 8'sd0;
        a3 = 8'sd0;

        b0 = 8'sd0;
        b1 = 8'sd0;
        b2 = 8'sd0;
        b3 = 8'sd0;


        case (state)

            // =================================================
            // IDLE
            // =================================================

            STATE_IDLE: begin

                busy = 1'b0;

            end


            // =================================================
            // STREAM
            // =================================================

            STATE_STREAM: begin

                busy = 1'b1;

                compute_enable = 1'b1;


                case (cycle)

                    // =================================================
                    // CYCLE 0
                    //
                    // A:
                    //
                    // 1
                    //
                    // B:
                    //
                    // B00
                    // =================================================

                    4'd0: begin

                        a0 = A0_reg[7:0];

                        a1 = 0;
                        a2 = 0;
                        a3 = 0;


                        b0 = B0_reg[7:0];

                        b1 = 0;
                        b2 = 0;
                        b3 = 0;

                    end


                    // =================================================
                    // CYCLE 1
                    //
                    // A:
                    //
                    // A01
                    // A10
                    //
                    // B:
                    //
                    // B10
                    // B01
                    // =================================================

                    4'd1: begin

                        a0 = A0_reg[15:8];

                        a1 = A1_reg[7:0];

                        a2 = 0;
                        a3 = 0;


                        b0 = B1_reg[7:0];

                        b1 = B0_reg[15:8];

                        b2 = 0;
                        b3 = 0;

                    end


                    // =================================================
                    // CYCLE 2
                    //
                    // A:
                    //
                    // A02
                    // A11
                    // A20
                    //
                    // B:
                    //
                    // B20
                    // B11
                    // B02
                    // =================================================

                    4'd2: begin

                        a0 = A0_reg[23:16];

                        a1 = A1_reg[15:8];

                        a2 = A2_reg[7:0];

                        a3 = 0;


                        b0 = B2_reg[7:0];

                        b1 = B1_reg[15:8];

                        b2 = B0_reg[23:16];

                        b3 = 0;

                    end


                    // =================================================
                    // CYCLE 3
                    //
                    // A:
                    //
                    // A03
                    // A12
                    // A21
                    // A30
                    //
                    // B:
                    //
                    // B30
                    // B21
                    // B12
                    // B03
                    // =================================================

                    4'd3: begin

                        a0 = A0_reg[31:24];

                        a1 = A1_reg[23:16];

                        a2 = A2_reg[15:8];

                        a3 = A3_reg[7:0];


                        b0 = B3_reg[7:0];

                        b1 = B2_reg[15:8];

                        b2 = B1_reg[23:16];

                        b3 = B0_reg[31:24];

                    end


                    // =================================================
                    // CYCLE 4
                    //
                    // A:
                    //
                    // A13
                    // A22
                    // A31
                    //
                    // B:
                    //
                    // B31
                    // B22
                    // B13
                    // =================================================

                    4'd4: begin

                        a0 = 0;

                        a1 = A1_reg[31:24];

                        a2 = A2_reg[23:16];

                        a3 = A3_reg[15:8];


                        b0 = 0;

                        b1 = B3_reg[15:8];

                        b2 = B2_reg[23:16];

                        b3 = B1_reg[31:24];

                    end


                    // =================================================
                    // CYCLE 5
                    //
                    // A:
                    //
                    // A23
                    // A32
                    //
                    // B:
                    //
                    // B32
                    // B23
                    // =================================================

                    4'd5: begin

                        a0 = 0;
                        a1 = 0;

                        a2 = A2_reg[31:24];

                        a3 = A3_reg[23:16];


                        b0 = 0;
                        b1 = 0;

                        b2 = B3_reg[23:16];

                        b3 = B2_reg[31:24];

                    end


                    // =================================================
                    // CYCLE 6
                    //
                    // A:
                    //
                    // A33
                    //
                    // B:
                    //
                    // B33
                    // =================================================

                    4'd6: begin

                        a0 = 0;
                        a1 = 0;
                        a2 = 0;

                        a3 = A3_reg[31:24];


                        b0 = 0;
                        b1 = 0;
                        b2 = 0;

                        b3 = B3_reg[31:24];

                    end


                    default: begin

                        a0 = 0;
                        a1 = 0;
                        a2 = 0;
                        a3 = 0;

                        b0 = 0;
                        b1 = 0;
                        b2 = 0;
                        b3 = 0;

                    end

                endcase

            end


            // =================================================
            // FLUSH
            // =================================================

            STATE_FLUSH: begin

                busy = 1'b1;

                compute_enable = 1'b1;

                a0 = 0;
                a1 = 0;
                a2 = 0;
                a3 = 0;

                b0 = 0;
                b1 = 0;
                b2 = 0;
                b3 = 0;

            end


            // =================================================
            // DONE
            // =================================================

            STATE_DONE: begin

                busy = 1'b0;

                done = 1'b1;

            end


            default: begin

                busy = 1'b0;

                done = 1'b0;

            end

        endcase

    end

endmodule